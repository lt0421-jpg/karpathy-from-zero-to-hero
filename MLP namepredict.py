C = torch.randn((27,10))
parameters = [C,W1,W2,b1,b2]
for p in parameters:
  p.requires_grad = True

lre = torch.linspace(-3, 0, 30000)
lrs = 10**lre

lri = []
lossi = []
stepi = []

for i in range(50000):
  #minibath construct
  ix = torch.randint(0,Xtr.shape[0],(32,)) #(32,)是啥意思
  #forward pass
  emb = C[Xtr[ix]]
  h = torch.tanh(emb.view(-1,30) @ W1+b1)
  logits = h @ W2 + b2
  loss = F.cross_entropy(logits,Ytr[ix])  #自带的交叉熵更好用 loss是一个张量
  #print(loss.item())
  #backward pass
  for p in parameters:
    p.grad = None
  loss.backward()
  #update
  #lr = lrs[i]   #先寻找最佳的lr
  lr = 0.1
  for p in parameters:
    p.data += -lr * p.grad
  #track states
  lossi.append(loss.log10().item())
  stepi.append(i)

