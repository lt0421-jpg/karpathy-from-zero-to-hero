#build dataset

def build_dataset(words):
  block_size = 3 #context length: 3 words to predict 1 word
  X, Y =[], []

  for w in words:

    context = [0] * block_size
    for ch in w + '.':
      ix = stoi[ch]
      X.append(context)
      Y.append(ix)
      context = context[1:] + [ix]

  X = torch.tensor(X)
  Y = torch.tensor(Y)
  print(X.shape,Y.shape)
  return X, Y

import random
